function pack(id, top, bot) {
  const lines = [...top, ...HOUSE, ...bot];
  if (lines.length !== 31) throw new Error(`map ${id}: ${lines.length} lignes`);
  for (let i = 0; i < lines.length; i += 1) {
    if (lines[i].length !== 28) throw new Error(`map ${id} L${i} len=${lines[i].length} ${lines[i]}`);
  }
  return lines;
}

